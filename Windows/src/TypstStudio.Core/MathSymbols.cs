    public static string Insertion(string text, int offset, string name)
    {
        var prefix = text[..Math.Clamp(offset, 0, text.Length)];
        var math = TypstEditing.Highlight(prefix).Count(s => s.Style == 5 && s.Length == 1 && prefix[s.Start] == '$') % 2 == 1;
        return math ? " " + name + " " : "$ " + name + " $";
    }
